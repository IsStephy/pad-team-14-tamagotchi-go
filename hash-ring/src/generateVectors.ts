// Writes ../test-vectors.json: inputs and the answers this TypeScript ring
// gives for them. A port to another language (the Go one in ../go, or one
// copied into a service) is correct when it reproduces every answer.
//
//   npm run vectors
//
// Re-generate ONLY when the algorithm changes on purpose - and then every
// service's copy of the ring has to change with it, or services would look
// for the same key on different nodes.

import fs from "fs";
import path from "path";
import { HashRing, VIRTUAL_NODES, hash32 } from "./hashRing";

// Keys shaped like the real ones (<service>:<entity>:<id>), plus edge cases:
// the empty string, non-ASCII text (UTF-8 multi-byte), and very long keys.
const sampleKeys: string[] = [
  "",
  "a",
  "cache-1#0",
  "cache-2#159",
  "guild-service:guild:3f2a9c1b-7d4e-4b8a-9c1d-2e3f4a5b6c7d",
  "guild-service:user-guilds:user-42",
  "package-registry-service:package:9b1e0c55-1a2b-4c3d-8e9f-0a1b2c3d4e5f",
  "package-registry-service:packages:v7:5d41402abc4b2a76",
  "gateway:token:e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
  "map-service:location:Ștefan",
  "tamagotchi-service:tamagotchi:🐉",
  "x".repeat(1000),
];
for (let i = 0; i < 200; i++) {
  sampleKeys.push(`battle-service:battle:${i}`);
}

// The node sets services will really use, plus a 4th node (for scaling up),
// a single node, and very few virtual nodes (so gaps are big and the
// wrap-around at the end of the ring is common).
const rings: { nodes: string[]; virtualNodes: number }[] = [
  { nodes: ["cache-1", "cache-2", "cache-3"], virtualNodes: VIRTUAL_NODES },
  { nodes: ["cache-1", "cache-2", "cache-3", "cache-4"], virtualNodes: VIRTUAL_NODES },
  { nodes: ["cache-1"], virtualNodes: VIRTUAL_NODES },
  { nodes: ["cache-1", "cache-2", "cache-3"], virtualNodes: 1 },
];

// For the 1-virtual-node ring, make sure at least one key lands past the last
// point, so a port that forgets the wrap-around fails the vectors.
const tiny = rings[3];
const maxPoint = Math.max(...tiny.nodes.map((n) => hash32(`${n}#0`)));
for (let i = 0; ; i++) {
  const key = `wrap-around:${i}`;
  if (hash32(key) > maxPoint) {
    sampleKeys.push(key);
    break;
  }
}

const vectors = {
  description:
    "Expected answers of the shared consistent-hash ring. Every port must reproduce all of them. Generated by `npm run vectors` in hash-ring/; do not edit by hand.",
  algorithm: {
    hash: "FNV-1a 32-bit over the UTF-8 bytes (offset basis 0x811c9dc5, prime 0x01000193), then murmur3 fmix32",
    virtualNodeLabel: "<node>#<i> for i in 0 .. virtualNodes-1",
    order: "points sorted by hash ascending, ties by node name (byte order)",
    lookup: "first point with hash >= hash32(key), wrapping to the first point",
  },
  hashes: sampleKeys.map((input) => ({ input, hash: hash32(input) })),
  lookups: rings.map(({ nodes, virtualNodes }) => {
    const ring = new HashRing(nodes, virtualNodes);
    return {
      nodes,
      virtualNodes,
      cases: sampleKeys.map((key) => ({ key, node: ring.nodeFor(key) })),
    };
  }),
};

// dist/src/generateVectors.js -> hash-ring/test-vectors.json
const out = path.join(__dirname, "..", "..", "test-vectors.json");
fs.writeFileSync(out, JSON.stringify(vectors, null, 2) + "\n");
console.log(`wrote ${out}: ${vectors.hashes.length} hashes, ${rings.length} rings`);
